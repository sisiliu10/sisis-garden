"""Build the shiba sprite sheet from art/dog-sprite.png (the original, untouched).
The PNG is an upscaled 20x18 pixel sprite; we read it back at its own pixel grid (centre of each cell),
then make animation frames only by moving or hiding pixels of that sprite. Nothing is redrawn.
Writes src/game/10-dogsheet.js (sheet as a data URL + frame list). Run: python3 tools/dog_sheet.py"""
import base64, io, json, os
from PIL import Image
R = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = Image.open(R + '/art/dog-sprite.png').convert('RGBA')
NX, NY = 20, 18
sx, sy = src.width / NX, src.height / NY
P = {'o': (122, 30, 20), 'e': (40, 8, 4), 'b': (252, 145, 4), 'm': (250, 119, 12), 'd': (248, 96, 18), 'l': (253, 215, 167)}
def cell(i, j):
    px = sorted((src.getpixel((int(sx * i + sx * a), int(sy * j + sy * b))) for a in (.35, .5, .65) for b in (.35, .5, .65)), key=sum)[4]
    if px[3] < 128: return '.'
    return min(P, key=lambda k: sum((x - y) ** 2 for x, y in zip(P[k], px[:3])))
base = [[cell(i, j) for i in range(NX)] for j in range(NY)]
W = NX + 2  # room for the tail to swing
def blank(): return [['.'] * W for _ in range(NY)]
def copy(g): return [r[:] + ['.'] * (W - len(r)) for r in g]
def move(g, box, dx, dy, clear=True):
    """move the pixels inside box (x0,y0,x1,y1 inclusive) by dx,dy; only non-transparent pixels are carried"""
    x0, y0, x1, y1 = box; out = copy(g); pts = []
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            if g[y][x] != '.': pts.append((x, y, g[y][x]))
            if clear: out[y][x] = '.'
    for x, y, c in pts:
        if 0 <= x + dx < W and 0 <= y + dy < NY: out[y + dy][x + dx] = c
    # anything outside the box that was under the moved area keeps its own pixel unless covered
    for y in range(NY):
        for x in range(W):
            if out[y][x] == '.' and not (x0 <= x <= x1 and y0 <= y <= y1) and x < len(g[y]) and g[y][x] != '.':
                out[y][x] = g[y][x]
    return out
def recolor(g, pts, c):
    out = copy(g)
    for x, y in pts: out[y][x] = c
    return out
eyes = [(x, y) for y in range(NY) for x in range(NX) if base[y][x] == 'e' and y <= 6]
mouth = [(x, y) for y in range(7, 10) for x in range(NX) if base[y][x] == 'e']
TAIL = (15, 5, 19, 7)      # upper part of the curled tail
EARS = (1, 0, 11, 2)
HEAD = (0, 0, 11, 12)
F = {}
F['idle'] = copy(base)
F['breath'] = move(base, (0, 0, 19, 12), 0, 1)
F['blink'] = recolor(base, eyes, 'b')
F['walk1'] = move(base, (2, 15, 7, 17), 0, -1)
F['walk2'] = move(base, (10, 15, 18, 17), 0, -1)
F['wag1'] = move(base, TAIL, 1, 0)
F['wag2'] = move(base, TAIL, 1, -1)
sad = move(move(base, EARS, 0, 1), TAIL, 0, 2)
sad = recolor(sad, [(x, y) for (x, y) in mouth if y == min(m[1] for m in mouth)], 'l')  # smile corners gone
F['sad'] = sad
F['sadb'] = move(sad, (0, 0, 19, 12), 0, 1)
sl = recolor(recolor(base, eyes, 'o'), mouth, 'l')
sl = move(sl, EARS, 0, 1)
sl = move(sl, (0, 0, 19, 14), 0, 3)      # lie down: body sinks over the legs
# close the belly with the sprite's own outline colour, so the lying dog does not look cut off by the floor or the rug
row = sl[NY - 1]; cols = [x for x, c in enumerate(row) if c != '.']
if cols:
    for x in range(min(cols), max(cols) + 1): row[x] = 'o'
for y in range(NY - 3, NY - 1):  # the rows just above it: fill gaps between the legs with the body colour
    r = sl[y]; cols = [x for x, c in enumerate(r) if c != '.']
    if cols:
        for x in range(min(cols) + 1, max(cols)):
            if r[x] == '.': r[x] = 'b'
F['sleep'] = sl
F['sleepb'] = move(sl, (0, 3, 19, 12), 0, 1)
F['eat1'] = move(base, HEAD, 0, 1)
F['eat2'] = move(base, HEAD, 0, 2)
names = list(F)
sheet = Image.new('RGBA', (W * len(names), NY * 2), (0, 0, 0, 0))
for n, k in enumerate(names):
    for y in range(NY):
        for x in range(W):
            c = F[k][y][x]
            if c == '.': continue
            sheet.putpixel((n * W + x, y), P[c] + (255,))
            sheet.putpixel((n * W + (W - 1 - x), NY + y), P[c] + (255,))  # second row: facing right
buf = io.BytesIO(); sheet.save(buf, 'PNG', optimize=True)
sheet.save(R + '/art/dog-sheet.png')
url = 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()
open(R + '/src/game/10-dogsheet.js', 'w').write(
    '/* generated by tools/dog_sheet.py from art/dog-sprite.png; do not edit by hand */\n'
    f'const DOG_SHEET={json.dumps(url)}, DOG_W={W}, DOG_H={NY}, DOG_FR={json.dumps({k: i for i, k in enumerate(names)})};\n')
print('frames', names, 'sheet', sheet.size, len(url), 'bytes')
